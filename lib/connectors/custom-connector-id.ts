/* ================================================================== *
 * CUSTOM CONNECTOR CONNECTION-ID CONVENTION — connector platform
 * audit, Fase D2. connections.connector_id (migrations/
 * 0002_connectors.sql) is a free TEXT column, never a foreign key
 * into the static CONNECTOR_REGISTRY — so a Custom Connector's
 * concrete, per-org authorizations can be represented as ordinary
 * `connections` rows, with no schema change, by prefixing the
 * connector_id with "custom_". This is the one place that prefix is
 * generated/parsed, so it can never drift into two different string
 * formats in two different call sites.
 *
 * A custom_connectors.id is already "cconn_<uuid>" — the prefix here
 * layers on top ("custom_cconn_<uuid>"), never collides with a static
 * ConnectorDefinition.id (those are short, hand-picked strings like
 * "connector_salesforce", never starting with "custom_cconn_").
 * ================================================================== */

const PREFIX = "custom_"

export function customConnectorConnectorId(customConnectorId: string): string {
  return `${PREFIX}${customConnectorId}`
}

/** Returns the underlying custom_connectors.id if `connectorId` was
 * generated by customConnectorConnectorId(), else null — lets a
 * caller iterating `connections` rows tell a custom-connector
 * Connection apart from a static one without guessing at string
 * shape in more than one place. */
export function parseCustomConnectorId(connectorId: string): string | null {
  return connectorId.startsWith(PREFIX) ? connectorId.slice(PREFIX.length) : null
}
